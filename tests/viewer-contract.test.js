"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "gallery.html"), "utf8");
const gallery = fs.readFileSync(path.join(root, "gallery.js"), "utf8");
const viewer = fs.readFileSync(path.join(root, "viewers/media-viewer.js"), "utf8");
const css = fs.readFileSync(path.join(root, "viewers/media-viewer.css"), "utf8");

const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, "HTML IDs must be unique");
assert.equal(ids.filter(id => id === "mediaViewer").length, 1, "exactly one viewer dialog must exist");
assert.ok(!html.includes('id="lightbox"'), "legacy dialog must be removed");
assert.ok(!html.includes('id="fancyboxViewer"'), "dynamically-created legacy viewer must be removed");
assert.ok(html.includes('src="viewers/media-viewer.js"'));
assert.ok(html.includes('href="viewers/media-viewer.css"'));
assert.ok(gallery.includes('window.ExtMediaViewer.open(data.items, index, item.type, trigger)'));
assert.ok(viewer.includes('item?.type === expectedType'), "viewer must filter strictly by media type");
assert.ok(viewer.includes('video.pause()') && viewer.includes('video.removeAttribute("src")'), "video must be stopped and detached");
assert.ok(viewer.includes("requestFullscreen"), "fullscreen control must use the browser fullscreen API");
assert.ok(viewer.includes("renderThumbs"), "thumbnail rail must be implemented");
assert.ok(viewer.includes("ArrowLeft") && viewer.includes("ArrowRight"), "keyboard navigation must be implemented");
assert.ok(viewer.includes('event.pointerType === "touch"'), "touch gesture handling must be implemented");
assert.ok(css.includes(".viewer-thumbs") && css.includes(".viewer-thumb[aria-current=\"true\"]"));
console.log("viewer-contract.test.js: OK");
